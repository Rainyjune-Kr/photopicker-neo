export function setLanguage(locale: string) {
  document.documentElement.lang = /^ko(?:[-_]|$)/i.test(locale) ? "ko" : "en";
}
export function t(korean: string) {
  return document.documentElement.lang === "ko" ? korean : english[korean] ?? korean;
}
export function backendMessage(cause: unknown) {
  const message = String(cause);
  const split = message.indexOf(" · ");
  return split < 0 ? t(message) : t(message.slice(0, split)) + message.slice(split);
}
